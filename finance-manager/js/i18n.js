let _lang = "en";

function setLang(lang) {
  _lang = (lang === "bn") ? "bn" : "en";
  document.documentElement.lang = _lang;
}
function getLang() { return _lang; }

/** Translate: t('key') or t('key', {n: 5}) */
function t(key, vars) {
  let s = (I18N[_lang] && I18N[_lang][key]) != null ? I18N[_lang][key] : (I18N.en[key] != null ? I18N.en[key] : key);
  if (vars) for (const k in vars) s = s.split("{" + k + "}").join(vars[k]);
  return s;
}

/** Convert ASCII digits to Bengali digits when lang = bn */
function locDigits(str) {
  if (_lang !== "bn") return String(str);
  const map = { "0": "০", "1": "১", "2": "২", "3": "৩", "4": "৪", "5": "৫", "6": "৬", "7": "৭", "8": "৮", "9": "৯" };
  return String(str).replace(/[0-9]/g, d => map[d]);
}

/** Apply translations to all [data-i18n] / [data-i18n-ph] nodes */
function applyI18n(root) {
  (root || document).querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.getAttribute("data-i18n")); });
  (root || document).querySelectorAll("[data-i18n-ph]").forEach(el => { el.placeholder = t(el.getAttribute("data-i18n-ph")); });
}
